const pad = (n: number) => String(n).padStart(2, '0');

/** Demo 資料的英文日期（Oct 19, 2026 21:14、Oct 29）改成 2026/10/19 21:14、10/29。 */
function date(text: string): string {
  const ms = Date.parse(text);
  if (Number.isNaN(ms)) return text;
  const d = new Date(ms);
  const day = `${d.getMonth() + 1}/${d.getDate()}`;
  const withYear = /\d{4}/.test(text) ? `${d.getFullYear()}/${day}` : day;
  return /\d{1,2}:\d{2}/.test(text) ? `${withYear} ${pad(d.getHours())}:${pad(d.getMinutes())}` : withYear;
}

const SIDES: Record<string, string> = { yes: '是', no: '否', up: '漲', down: '跌' };

function timeLeft(minutes: number): string {
  const d = Math.floor(minutes / 1440);
  const h = Math.floor((minutes % 1440) / 60);
  const m = minutes % 60;
  if (d) return `${d} 天 ${h} 小時`;
  if (h) return `${h} 小時 ${m} 分`;
  return `${m} 分`;
}

